#remove ERCCs, needs counts table 
prepocessMTX <- function(raw.mtx, remove.pattern = 'ERCC', geneIDcol = NULL, chromosomeCol = NULL, na2zero = TRUE){
  
  if(!is.null(geneIDcol)){
    print('Setting geneID as row names')
    rownames(raw.mtx) <- raw.mtx[[geneIDcol]]
    raw.mtx[[geneIDcol]] <- NULL
  }else{
    print('Assuming row.names == geneID')
  }
  
  if(!is.null(chromosomeCol)){
    print('Removing chromosome column')
    raw.mtx[[chromosomeCol]] <- NULL
  }
  
  ##// Remove rows matching pattern
  mtx <- raw.mtx[!grepl(remove.pattern, rownames(raw.mtx)),]
  
  if(na2zero){
    mtx[is.na(mtx)] <- 0
  }
  return(mtx)
}



#get counts per section, needs named list of count matrices and sample ID
getCPS <- function(mtx.list, sid, combine = TRUE, plotAscending = FALSE){
  
  ##// Compute CPS per matrix
  cps.list <- lapply(names(mtx.list), function(x){
    ##// Compute counts per section
    cps <- data.frame(colSums(mtx.list[[x]]))
    colnames(cps) <- 'CPS'
    cps$Section <- colnames(mtx.list[[x]])
    cps$dataset <- x
    return(cps)
  })
  
  
  ##// Format plots
  if(combine){
    cps.list <- list(do.call(rbind, cps.list))
  }
  
  #// Reorder variable if plotting in ascending order
  if(plotAscending){
    cps.list <- lapply(cps.list, function(x){
      x <- x %>% group_by(Section) %>% mutate('SumCount' = sum(CPS)) %>% ungroup()
      gps.reorder <- x %>% arrange(SumCount) %>% mutate(Section = factor(Section, levels = unique(Section)))
    })
  }else{
    #// We need a SumCount value anyway
    cps.list <- lapply(cps.list, function(x){
      x <- x %>% group_by(Section) %>% mutate('SumCount' = CPS) %>% ungroup()
    })
  }
  
  #// Plot
  p <- lapply(cps.list, function(x){
    p <- ggplot(x, aes(x = Section, y = CPS, fill = dataset)) + geom_bar(stat = 'identity') + theme_bw() +
      ggtitle(paste('Genes per section', sid, sep = ' - ')) + xlab('Section') + ylab('Total UMI count') + 
      theme(plot.title = element_text(hjust = 0.5)) + scale_fill_brewer(palette = 'Greens') + presentation
  })
  return(list(p, cps.list))
}


