## normalization to transcripts per ten million

tenM_normalize <- function(my_data){
  total_transcripts <- sum(my_data) #sum of all raw counts
  ttm_factor <- (total_transcripts/1E7) #factor 'per ten million'
  tenM_mat <- as_tibble(my_data/ttm_factor) # divide each cell by factor above
  return(tenM_mat)
}
## normalization each column to median of total dataset
median_normalize <- function(mat) {
  cs <- colSums(mat[,-1], na.rm = T)
  norm_mat <- as_tibble((t(t(mat[,-1]) / cs)) * median(cs))%>%
    add_column(GENEID = mat$GENEID, .before = 1)
  return(norm_mat)
}






