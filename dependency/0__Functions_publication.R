runSCT <- function(At.mtx, Hs.mtx, combineMTX = TRUE, min.cells = c(2), min.features = c(300), regressVars = FALSE){
  
  #"If combineMTX = FALSE, min.cells and min.features must be length 2
  #"Returns a list of seurat objects
  
  ##// Create seurat object from matrices
  if(combineMTX){
    warning('Combining matrices')
    mtx <-  rbind(At.mtx, Hs.mtx)
    sobj.list <- list(CreateSeuratObject(counts = mtx, min.cells = min.cells, min.features = min.features))
  }else{
    stopifnot(length(min.cells) & length(min.features) == 2)
    sobj.list <- mapply(x = list(At.mtx, Hs.mtx), y  = min.cells, z = min.features, SIMPLIFY=FALSE, function(x, y, z){
      CreateSeuratObject(counts = x, min.cells = y, min.features = z)
    })
  }
  
  ##// Normalize data
  sobj.list <- lapply(sobj.list, function(x){
    ##// Compute metadata features
    x <- PercentageFeatureSet(x, pattern = "^ATM", col.name = "percent.mt")
    x <- PercentageFeatureSet(x, pattern = "^ATC", col.name = "percent.cp")
    x <- PercentageFeatureSet(x, pattern = "^transcript:Hsc", col.name = "percent.Hs")
    
    set.seed(42)
    ##// Normalize
    if(regressVars){
      x <- SCTransform(x, vars.to.regress = c('percent.mt', 'percent.cp'), return.only.var.genes = FALSE, vst.flavor = 'v2', min_cells = 1)
    }else{
      x <- SCTransform(x, return.only.var.genes = FALSE, vst.flavor = 'v2', min_cells = 1)
    }
    return(x)
  })
}



findSimilar <- function(reference, mtx, method = 'Pearson', threshold = 0.9, n = 10, forceN = TRUE){
  
  ##// Subset matrices
  ref.mtx <- mtx[reference,]
  target.mtx <- mtx[!rownames(mtx) %in% reference,]
  
  ##// Compute correlations
  cor.df <- data.frame(apply(target.mtx, 1, function(x) cor(ref.mtx, x, method = method)))
  
  #// Reformat dataframe
  colnames(cor.df) <- 'Correlation'
  cor.df$Gene <- rownames(target.mtx)
  
  #// Select genes
  cor.df <- cor.df %>% arrange(desc(Correlation))
  
  #// Subset on genes passing threshold
  if(nrow(subset(cor.df, Correlation >= threshold)) < n & forceN){
    warning(paste('Unable to find ', n, 'Features passing ', threshold, '. Returning top ', n))
    return(cor.df[1:n,])
  }else if(nrow(subset(cor.df, Correlation >= threshold)) > n & forceN == TRUE){
    warning(paste('More than ', n, 'Features passing ', threshold, '. Returning top ', n))
    return(cor.df[1:n,])
  }else{
    return(subset(cor.df, Correlation >= threshold))
  }
}

