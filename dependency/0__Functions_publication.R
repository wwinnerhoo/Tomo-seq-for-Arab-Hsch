## Function to save the cluster into seperate txt file
Save_clusters <- function(cluster_df,file_path) {
  wb <- createWorkbook()
  for (cluster_id in names(cluster_df)) {
    # Extract enrichment results
    cluster_each <- cluster_df[[cluster_id]]
    
    sheet_name <- paste0("Cluster_", cluster_id)
    addWorksheet(wb, sheet_name)
    # Write filtered results
    writeData(wb, sheet_name, cluster_each)
    print(paste("Saved sheet:", sheet_name))
    
    # Save workbook to an Excel file
    saveWorkbook(wb, file.path(getwd(), file_path), overwrite = TRUE)
    print(paste0("Excel file saved successfully! ", file_path))
  }
}

################ Elbow function


wcss_func <- function(k,matrix) {
  #matrix e.g. s78.wcss_mt
  
  set.seed(42)
  cluster_var <- kmeans(matrix, centers = k, nstart = 100) #$tot.withinss
  return(list(
    tot_withiness = cluster_var$tot.withinss,
    clusters = cluster_var$cluster
  ))
}

elbow_analysis <- function(per_matrix) {

  # Set range for k (e.g., 1 to 10)
  k_values <- 1:15

  # Use lapply to get a list of results for different k values
  wcss_result <- lapply(k_values, function(x)  wcss_func(x,per_matrix))

  # Extract tot.withinss values for plotting
  wcss_value <- sapply(wcss_result, function(x) x$tot_withiness)
  # Extract cluster assignments for each k (optional)
  cluster_assignment <- lapply(wcss_result, function(x) x$clusters)
  
  return(list(
    wcss_values = wcss_value,
    cluster_assignments = cluster_assignment
  ))
}


