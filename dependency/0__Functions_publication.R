### Function to reshape the count table, which generated by the SingleMultiomics pipeline
count_reshape <- function(count_table,sample_str){
  ### count_table: a dataframe with the first two columns as gene_id and gene_name, (colnames: X, X.1)
  ### columns: 3 to end: the count values for 384 sections in random order.
  ## sample_str: the string combined with the section number, e.g. "sample_" in "sample_96"
  
  count_table_df <- count_table[,c(3:length(colnames(count_table)))] 
  count_table_df <- count_table_df[,order(as.numeric(sub(".*_", "", colnames(count_table) [3:length(colnames(count_table))])))] # str_all <- colnames(s78_dedup) [3:length(colnames(s78_dedup))]
  # reshape the original count table
  ##count_table_reshape <- cbind(count_table[,c(1,2)],count_table_df) # not used
  count_table_reshape <- cbind(count_table[,c(1,2)],count_table_df[,1:96]) #count_table_df[,1:96], the first 96 sections of 384 sections
  
  # rename the frist two columns and keep the 96 sections. 
  colnames(count_table_reshape) <- c("Gene_id", "Chromosome", gsub(sample_str, "", colnames(count_table_reshape) [3:ncol(count_table_reshape)]))
  
  # replace the NA with ""
  count_table_reshape[is.na(count_table_reshape)] <- ""
  
  return(count_table_reshape)
}


### Normalization method: CPM-like normalization, and median scaling
CPM_Median_normalization <- function(gene_section_matrix){
  ### gene_section_matrix: a dataframe with the first two columns as gene_id and gene_name, 
  ### columns: 1-96: the count values for 96 sections in order; rows: the genes.
  
  # calculate the sum of each column
  col_sum <- colSums(gene_section_matrix)
  
  # CPM-like normalization
  gene_section_matrix_norm <- sweep(gene_section_matrix, 2, col_sum, FUN = "/")
  
  # median scaling
  median_col_sum <- median(col_sum)
  gene_section_matrix_norm <- sweep(gene_section_matrix_norm, 2, median_col_sum, FUN = "*")
  
  return(gene_section_matrix_norm)
}



